// Writes the defaults of src/shared/settings_table.ts to src/shared/default_settings.ts.
// The content script reads defaults but must not bundle the table and its checks, so it reads this copy instead.
// Usage: node tools/build_default_settings.ts --write | --check [--out path]

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SETTINGS_TABLE, type SettingName } from "../src/shared/settings_table.ts";

const out_flag = process.argv.indexOf("--out");
const module_path = out_flag >= 0 ? process.argv[out_flag + 1]! : fileURLToPath(new URL("../src/shared/default_settings.ts", import.meta.url));
const write = process.argv.includes("--write");
if (write === process.argv.includes("--check")) {
  console.error("usage: node tools/build_default_settings.ts --write | --check [--out path]");
  process.exit(2);
}

const default_constant_name = (name: SettingName): string => `DEFAULT_${name.toUpperCase()}`;

const defaulted = (Object.keys(SETTINGS_TABLE) as SettingName[]).filter((name) => "default" in SETTINGS_TABLE[name]);
const constants = defaulted.map((name) => `export const ${default_constant_name(name)}: Settings["${name}"] = ${JSON.stringify((SETTINGS_TABLE[name] as { default: unknown }).default)};`);
const entries = defaulted.map((name) => `  ${name}: ${default_constant_name(name)},`);

const next = `// Generated by tools/build_default_settings.ts from src/shared/settings_table.ts. Run \`just settings-defaults\` after a change there.

import type { Settings } from "./settings_table.ts";

// One constant per setting, so a bundle that reads one default (the content script) carries only that one.
${constants.join("\n")}

export const DEFAULT_SETTINGS: Settings = {
${entries.join("\n")}
};
`;

// A missing module is stale, the same as an outdated one.
if ((existsSync(module_path) ? readFileSync(module_path, "utf8") : undefined) !== next) {
  if (write) writeFileSync(module_path, next);
  else {
    console.error(`${module_path} is stale against src/shared/settings_table.ts; run \`just settings-defaults\``);
    process.exit(1);
  }
}
