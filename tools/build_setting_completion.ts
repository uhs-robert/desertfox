// Writes what the command line page needs of each setting to src/shared/setting_completion.ts.
// The page completes names and values and checks a name, but must not bundle the setting rules, so it reads this copy instead.
// Usage: node tools/build_setting_completion.ts --write | --check [--out path]

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SETTING_NAMES, SETTING_SPECS } from "../src/shared/settings_schema.ts";

const out_flag = process.argv.indexOf("--out");
const module_path = out_flag >= 0 ? process.argv[out_flag + 1]! : fileURLToPath(new URL("../src/shared/setting_completion.ts", import.meta.url));
const write = process.argv.includes("--write");
if (write === process.argv.includes("--check")) {
  console.error("usage: node tools/build_setting_completion.ts --write | --check [--out path]");
  process.exit(2);
}

const rows = SETTING_NAMES.map((name) => {
  const spec = SETTING_SPECS[name];
  return { name, settable: spec.settable, is_toggle: spec.is_toggle, is_list: spec.is_list, expectation: spec.expectation, values: spec.listed_values?.() ?? [] };
});

const next = `// Generated by tools/build_setting_completion.ts from src/shared/settings_schema.ts. Run \`just settings-defaults\` after a change to a setting, or to the theme names.

import type { SettingName } from "./settings_table.ts";

export type SettingCompletion = {
  name: SettingName;
  settable: boolean;
  is_toggle: boolean;
  is_list: boolean;
  expectation: string;
  // Words the command line offers after the name. Theme names and the new tab page are stored as of generation.
  values: readonly string[];
};

export const SETTING_COMPLETION: readonly SettingCompletion[] = ${JSON.stringify(rows, null, 2)};

const NAMES: ReadonlySet<string> = new Set(SETTING_COMPLETION.map((setting) => setting.name));

export const is_setting_name = (name: string): name is SettingName => NAMES.has(name);

export const completion_of = (name: SettingName): SettingCompletion => SETTING_COMPLETION.find((setting) => setting.name === name)!;
`;

// A missing module is stale, the same as an outdated one.
if ((existsSync(module_path) ? readFileSync(module_path, "utf8") : undefined) !== next) {
  if (write) writeFileSync(module_path, next);
  else {
    console.error(`${module_path} is stale against src/shared/settings_schema.ts; run \`just settings-defaults\``);
    process.exit(1);
  }
}
